"""Immutable evidence snapshots and workspace-scoped, append-only review events."""

from contextlib import contextmanager
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import secrets
import sqlite3
from urllib.parse import parse_qs, urlparse
import uuid

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
ACTIONS = ("Accept", "Defer", "Override priority")
PRIORITIES = ("High", "Medium", "Low")


class ReviewError(ValueError):
    """A validation or storage problem safe to display without credentials."""


def new_workspace_key():
    return secrets.token_urlsafe(32)


def workspace_digest(key):
    if not isinstance(key, str) or not re.fullmatch(r"[A-Za-z0-9_-]{43}", key):
        raise ReviewError("Use the complete 43-character recovery key generated by this app.")
    return hashlib.sha256(("productlens-review-v1:" + key).encode()).hexdigest()


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False, ensure_ascii=False)


def _records(frame, sort_by):
    # pandas converts nullable numeric/date values into portable JSON null/ISO dates.
    return json.loads(frame.sort_values(sort_by).reindex(sorted(frame.columns), axis=1)
                      .to_json(orient="records", date_format="iso", double_precision=15))


def make_snapshot(evidence, groups, scores, semantic_config):
    snapshot = dict(
        version="review-v1", scoring_protocol="scoring-v1", semantic_config=semantic_config,
        weights=scores.weights, normalisation=scores.normalisation, common_confidence=scores.confidence,
        rows=_records(evidence.rows, ["feedback_id"]), accounts=_records(evidence.accounts, ["customer_id"]),
        subgroup_effort=_records(evidence.subgroups, ["opportunity_id", "duplicate_group_id"]),
        assignments=_records(groups.assignments, ["feedback_id"]),
        opportunities=_records(groups.opportunities, ["opportunity_id"]),
        scores=_records(scores.scores, ["opportunity_id"]),
        implementation_sha256={name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest() for name in (
            "productlens/ingestion.py", "productlens/grouping.py", "productlens/embeddings.py",
            "productlens/scoring.py", "productlens/reviews.py")})
    encoded = canonical(snapshot)
    return hashlib.sha256(encoded.encode()).hexdigest(), snapshot


class ReviewStore:
    def __init__(self, sqlite_path=None, postgres_url=None):
        if bool(sqlite_path) == bool(postgres_url):
            raise ReviewError("Configure exactly one review storage backend.")
        self.path = Path(sqlite_path) if sqlite_path else None
        self._postgres_url = postgres_url
        if postgres_url and urlparse(postgres_url).scheme not in {"postgres", "postgresql"}:
            raise ReviewError("Review database must use a PostgreSQL connection URL.")

    @classmethod
    def from_settings(cls, settings=None):
        settings = os.environ if settings is None else settings
        mode = settings.get("PRODUCTLENS_DEPLOYMENT", "local")
        if mode not in {"local", "cloud"}:
            raise ReviewError("PRODUCTLENS_DEPLOYMENT must be local or cloud.")
        url = settings.get("PRODUCTLENS_DATABASE_URL")
        if mode == "cloud":
            if not url:
                raise ReviewError("Cloud review storage needs PRODUCTLENS_DATABASE_URL. Local-file fallback is disabled.")
            sslmode = parse_qs(urlparse(url).query).get("sslmode", [""])
            if sslmode != ["require"] and sslmode != ["verify-ca"] and sslmode != ["verify-full"]:
                raise ReviewError("Cloud PostgreSQL URL must specify sslmode=require, verify-ca or verify-full.")
        if url:
            return cls(postgres_url=url)
        return cls(sqlite_path=settings.get("PRODUCTLENS_REVIEW_DB", str(ROOT / "data/private/reviews.sqlite3")))

    @property
    def description(self):
        return "PostgreSQL database" if self._postgres_url else "Local SQLite file (not cloud-durable)"

    @contextmanager
    def _connection(self):
        connection = None
        try:
            if self._postgres_url:
                import psycopg
                from psycopg.rows import dict_row
                connection = psycopg.connect(self._postgres_url, connect_timeout=5, row_factory=dict_row)
                sequence = "BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY"
            else:
                self.path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
                connection = sqlite3.connect(self.path, timeout=5)
                self.path.chmod(0o600)
                connection.row_factory = sqlite3.Row
                connection.execute("PRAGMA foreign_keys = ON")
                sequence = "INTEGER PRIMARY KEY AUTOINCREMENT"
            connection.execute("""CREATE TABLE IF NOT EXISTS productlens_review_snapshots (
                workspace TEXT NOT NULL, context_id TEXT NOT NULL, payload TEXT NOT NULL,
                PRIMARY KEY (workspace, context_id))""")
            connection.execute(f"""CREATE TABLE IF NOT EXISTS productlens_review_events (
                sequence {sequence}, event_id TEXT NOT NULL UNIQUE, workspace TEXT NOT NULL,
                context_id TEXT NOT NULL, opportunity_id TEXT NOT NULL, action TEXT NOT NULL,
                manual_priority TEXT, reason TEXT NOT NULL, reviewer TEXT NOT NULL, created_at TEXT NOT NULL,
                FOREIGN KEY (workspace, context_id) REFERENCES productlens_review_snapshots(workspace, context_id))""")
            connection.execute("CREATE INDEX IF NOT EXISTS productlens_review_scope ON productlens_review_events(workspace, context_id)")
            yield connection
            connection.commit()
        except ReviewError:
            if connection:
                connection.rollback()
            raise
        except Exception:
            if connection:
                connection.rollback()
            raise ReviewError("Review storage is unavailable. Check the backend configuration and write access; no save was confirmed.") from None
        finally:
            if connection:
                connection.close()

    def _execute(self, connection, sql, values=()):
        return connection.execute(sql.replace("?", "%s") if self._postgres_url else sql, values)

    def save(self, key, context_id, snapshot, opportunity_id, action, reason, reviewer="", manual_priority=None):
        workspace = workspace_digest(key)
        if action not in ACTIONS:
            raise ReviewError("Choose accept, defer or override priority.")
        if not isinstance(reason, str) or not reason.strip() or len(reason) > 4000:
            raise ReviewError("Provide a reason between 1 and 4,000 characters.")
        if not isinstance(reviewer, str) or len(reviewer) > 100:
            raise ReviewError("Reviewer label must be at most 100 characters.")
        if action == "Override priority":
            if manual_priority not in PRIORITIES:
                raise ReviewError("An override needs a High, Medium or Low manual priority.")
        elif manual_priority is not None:
            raise ReviewError("Only an override may set a manual priority.")
        encoded = canonical(snapshot)
        if hashlib.sha256(encoded.encode()).hexdigest() != context_id:
            raise ReviewError("Snapshot identity does not match its evidence; recompute before saving.")
        if snapshot.get("version") != "review-v1" or opportunity_id not in {row["opportunity_id"] for row in snapshot.get("scores", [])}:
            raise ReviewError("Selected opportunity does not belong to this review snapshot.")
        event_id = str(uuid.uuid4())
        created = datetime.now(timezone.utc).isoformat(timespec="microseconds")
        with self._connection() as connection:
            self._execute(connection, """INSERT INTO productlens_review_snapshots(workspace,context_id,payload)
                VALUES (?,?,?) ON CONFLICT (workspace,context_id) DO NOTHING""", (workspace, context_id, encoded))
            self._execute(connection, """INSERT INTO productlens_review_events
                (event_id,workspace,context_id,opportunity_id,action,manual_priority,reason,reviewer,created_at)
                VALUES (?,?,?,?,?,?,?,?,?)""", (event_id, workspace, context_id, opportunity_id, action,
                manual_priority, reason.strip(), reviewer.strip(), created))
        return event_id

    def history(self, key):
        workspace = workspace_digest(key)
        with self._connection() as connection:
            rows = self._execute(connection, """SELECT sequence,event_id,context_id,opportunity_id,action,
                manual_priority,reason,reviewer,created_at FROM productlens_review_events
                WHERE workspace=? ORDER BY sequence DESC""", (workspace,)).fetchall()
        return [dict(row) for row in rows]

    def export(self, key):
        workspace = workspace_digest(key)
        with self._connection() as connection:
            events = self._execute(connection, """SELECT sequence,event_id,context_id,opportunity_id,action,
                manual_priority,reason,reviewer,created_at FROM productlens_review_events
                WHERE workspace=? ORDER BY sequence""", (workspace,)).fetchall()
            snapshots = self._execute(connection, "SELECT context_id,payload FROM productlens_review_snapshots WHERE workspace=? ORDER BY context_id",
                                      (workspace,)).fetchall()
        return dict(format="productlens-review-export-v1", events=[dict(row) for row in events],
                    snapshots={row["context_id"]: json.loads(row["payload"]) for row in snapshots})
